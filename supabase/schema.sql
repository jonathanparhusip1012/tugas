-- 1. Tabel utama klaim voucher
create table if not exists public.voucher_claims (
    id              bigint generated by default as identity primary key,
    tanggal         timestamptz  not null default now(),          -- tanggal & waktu klaim
    gps_ip          text         not null,                        -- "lat, lng" atau alamat IP
    metode          text         not null default 'TIDAK_TERSEDIA'
                    check (metode in ('GPS', 'IP', 'TIDAK_TERSEDIA')),
    latitude        double precision,
    longitude       double precision,
    akurasi         integer,                                      -- meter (hanya GPS)
    ip_address      text,                                         -- IP publik hasil lookup
    kota            text,
    provider        text,                                         -- ISP / organisasi
    nama            text,
    whatsapp        text,
    kode_voucher    text         not null unique,
    persetujuan     boolean      not null default true,           -- bukti consent pengunjung
    user_agent      text
);

comment on table  public.voucher_claims is 'Klaim voucher promo Koteshu Indonesia beserta data GPS/IP.';
comment on column public.voucher_claims.gps_ip is 'Koordinat "lat, lng" bila GPS tersedia, atau alamat IP bila tidak.';
comment on column public.voucher_claims.tanggal is 'Waktu klaim diterima (timestamptz).';

-- 2. Indeks untuk laporan harian
create index if not exists voucher_claims_tanggal_idx
    on public.voucher_claims (tanggal desc);

create index if not exists voucher_claims_whatsapp_idx
    on public.voucher_claims (whatsapp);

-- 3. Row Level Security
--    anon  : hanya boleh INSERT (klaim), TIDAK boleh membaca data orang lain
--    admin : membaca lewat Supabase Dashboard / service_role key
alter table public.voucher_claims enable row level security;

revoke all on public.voucher_claims from anon, authenticated;
grant insert on public.voucher_claims to anon;
grant usage, select on sequence public.voucher_claims_id_seq to anon;

drop policy if exists "pengunjung boleh mengirim klaim" on public.voucher_claims;

create policy "pengunjung boleh mengirim klaim"
    on public.voucher_claims
    for insert
    to anon
    with check (
        persetujuan is true
        and char_length(coalesce(nama, '')) between 2 and 80
        and char_length(coalesce(gps_ip, '')) between 1 and 255
        and char_length(coalesce(kode_voucher, '')) between 4 and 32
    );

